#!/usr/bin/env python3
"""Generates the English pages from the French source files, so Google can index them.

    index.html          -> en/index.html
    tarifs/index.html   -> en/pricing/index.html

Edit the French files (and the `en:` dictionary in index.html, or the data-en
attributes in tarifs/index.html), then run:  python3 tools/build_en.py
It also refreshes the FAQPage JSON-LD of both homepages from the visible FAQ.
"""
import html, json, re, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SITE = "https://sss.marketing"


def dicts(src):
    out = {}
    for lg in ("fr", "en"):
        m = re.search(r'^    %s:(\{"metaTitle".*\}),?\s*$' % lg, src, re.M)
        out[lg] = json.loads(m.group(1))
    return out


def set_attr(s, pattern, value):
    new, n = re.subn(pattern, lambda m: m.group(1) + html.escape(value, quote=True) + m.group(2), s, count=1)
    assert n == 1, pattern
    return new


def faq_jsonld(d):
    keys = sorted({int(k[3:-1]) for k in d if re.fullmatch(r"faq\d+Q", k)})
    items = [{"@type": "Question", "name": d[f"faq{k}Q"], "acceptedAnswer": {"@type": "Answer", "text": d[f"faq{k}A"]}} for k in keys]
    return json.dumps({"@context": "https://schema.org", "@type": "FAQPage", "mainEntity": items}, ensure_ascii=False, indent=2)


def replace_faq_ld(s, d):
    pat = r'(<!-- JSON-LD · FAQPage[^>]*-->\s*<script type="application/ld\+json">\s*).*?(\s*</script>)'
    new, n = re.subn(pat, lambda m: m.group(1) + faq_jsonld(d) + m.group(2), s, count=1, flags=re.S)
    assert n == 1, "faq json-ld"
    return new


def home():
    p = ROOT / "index.html"
    fr_src = p.read_text(encoding="utf-8")
    D = dicts(fr_src)
    # keep only the FAQ entries that are actually on the page
    on_page = set(re.findall(r'data-i="(faq\d+[QA])"', fr_src))
    for lg in D:
        D[lg] = {k: v for k, v in D[lg].items() if not re.fullmatch(r"faq\d+[QA]", k) or k in on_page}

    fr = replace_faq_ld(fr_src, D["fr"])
    for prop in ("og:title", "twitter:title"):
        fr = set_attr(fr, r'(<meta (?:property|name)="%s" content=")[^"]*(">)' % prop, D["fr"]["metaTitle"])
    for prop in ("og:description", "twitter:description"):
        fr = set_attr(fr, r'(<meta (?:property|name)="%s" content=")[^"]*(">)' % prop, D["fr"]["metaDesc"])
    if fr != fr_src:
        p.write_text(fr, encoding="utf-8")

    en = fr
    E = D["en"]
    # visible text
    en = re.sub(r'(<(\w+)\b[^>]*\sdata-i="([^"]+)"[^>]*>)([^<]*)(</\2>)',
                lambda m: m.group(1) + (html.escape(E[m.group(3)], quote=False) if m.group(3) in E else m.group(4)) + m.group(5), en)
    # links that have an English twin
    en = re.sub(r'href="([^"]*)"([^>]*)data-href-en="([^"]*)"', r'href="\3"\2data-href-en="\3"', en)
    # document language and head
    en = en.replace('<html lang="fr-CA" data-page-lang="fr">', '<html lang="en-CA" data-page-lang="en">', 1)
    en = re.sub(r"<title>[^<]*</title>", "<title>" + html.escape(E["metaTitle"], quote=False) + "</title>", en, count=1)
    en = set_attr(en, r'(<meta name="description" content=")[^"]*(">)', E["metaDesc"])
    en = set_attr(en, r'(<link rel="canonical" href=")[^"]*(">)', SITE + "/en/")
    en = set_attr(en, r'(<meta property="og:url" content=")[^"]*(">)', SITE + "/en/")
    en = en.replace('<meta property="og:locale" content="fr_CA">', '<meta property="og:locale" content="en_CA">', 1)
    en = en.replace('<meta property="og:locale:alternate" content="en_CA">', '<meta property="og:locale:alternate" content="fr_CA">', 1)
    for prop in ("og:title", "twitter:title"):
        en = set_attr(en, r'(<meta (?:property|name)="%s" content=")[^"]*(">)' % prop, E["metaTitle"])
    for prop in ("og:description", "twitter:description"):
        en = set_attr(en, r'(<meta (?:property|name)="%s" content=")[^"]*(">)' % prop, E["metaDesc"])
    en = set_attr(en, r'(<meta property="og:image:alt" content=")[^"]*(">)', "SSS. Google marketing for dental clinics, built to fill chairs.")
    en = replace_faq_ld(en, E)
    en = en.replace("<!-- French is the source document. /en/ is generated from it by tools/build_en.py; edit here, then rebuild. -->",
                    "<!-- GENERATED by tools/build_en.py from /index.html. Do not edit by hand. -->", 1)
    # language switch
    en = en.replace('<a class="lang-btn active" data-lang="fr" href="/" hreflang="fr" lang="fr" aria-current="true">FR</a>',
                    '<a class="lang-btn" data-lang="fr" href="/" hreflang="fr" lang="fr">FR</a>', 1)
    en = en.replace('<a class="lang-btn" data-lang="en" href="/en/" hreflang="en" lang="en">EN</a>',
                    '<a class="lang-btn active" data-lang="en" href="/en/" hreflang="en" lang="en" aria-current="true">EN</a>', 1)
    for a, b in (('aria-label="Principale"', 'aria-label="Main"'), ('aria-label="Positionnement"', 'aria-label="Positioning"'),
                 ('aria-label="Réservation"', 'aria-label="Booking"'), ('aria-label="Semaine précédente"', 'aria-label="Previous week"'),
                 ('aria-label="Semaine suivante"', 'aria-label="Next week"')):
        en = en.replace(a, b)
    out = ROOT / "en" / "index.html"
    out.parent.mkdir(exist_ok=True)
    out.write_text(en, encoding="utf-8")
    print("wrote en/index.html")


TARIFS_FR_TITLE = "Tarifs du marketing dentaire : 450 $ par mois par clinique | SSS"
TARIFS_EN_TITLE = "Dental Marketing Pricing: $450 per Month per Clinic | SSS"
TARIFS_EN_DESC = "$450 per month, per clinic, $500 setup, Google ad budget billed at cost. Free CDCP calculator, installed during one 30-minute call."


def pricing():
    p = ROOT / "tarifs" / "index.html"
    s = p.read_text(encoding="utf-8")
    # French source: titles, real English URL, redirect for old ?lang=en links
    s = re.sub(r"<title>[^<]*</title>", "<title>" + html.escape(TARIFS_FR_TITLE, quote=False) + "</title>", s, count=1)
    s = set_attr(s, r'(<meta property="og:title" content=")[^"]*(">)', TARIFS_FR_TITLE)
    s = s.replace('<link rel="alternate" hreflang="en-CA" href="https://sss.marketing/tarifs/?lang=en">',
                  '<link rel="alternate" hreflang="en-CA" href="https://sss.marketing/en/pricing/">')
    s = s.replace('<a href="/tarifs/?lang=en" hreflang="en" lang="en" id="lang-en">EN</a>',
                  '<a href="/en/pricing/" hreflang="en" lang="en" id="lang-en">EN</a>')
    redirect = '<script>(function(){var q=new URLSearchParams(location.search);if(q.get("lang")==="en"){q.delete("lang");var r=q.toString();location.replace("/en/pricing/"+(r?"?"+r:"")+location.hash);}})();</script>'
    s = re.sub(r'<script>(?:if\(/\[\?&\]lang=en|\(function\(\)\{var q=new URLSearchParams).*?</script>\n', '', s, count=1)
    s = s.replace('<meta charset="utf-8">', '<meta charset="utf-8">\n' + redirect, 1)
    # the in-page English swap is replaced by the generated page
    s = re.sub(r'<script>\n\(function \(\) \{\n  if \(new URLSearchParams\(location\.search\)\.get\("lang"\) !== "en"\) return;.*?\}\)\(\);\n</script>\n', "", s, count=1, flags=re.S)
    p.write_text(s, encoding="utf-8")

    en = s.replace(redirect + "\n", "")
    en = en.replace('<html lang="fr-CA">', '<html lang="en-CA">', 1)
    en = re.sub(r"<title>[^<]*</title>", "<title>" + html.escape(TARIFS_EN_TITLE, quote=False) + "</title>", en, count=1)
    en = set_attr(en, r'(<meta name="description" content=")[^"]*(">)', TARIFS_EN_DESC)
    en = set_attr(en, r'(<meta property="og:title" content=")[^"]*(">)', TARIFS_EN_TITLE)
    en = set_attr(en, r'(<meta property="og:description" content=")[^"]*(">)', "$450 per month, per clinic. Free CDCP calculator.")
    en = set_attr(en, r'(<meta property="og:url" content=")[^"]*(">)', SITE + "/en/pricing/")
    en = set_attr(en, r'(<link rel="canonical" href=")[^"]*(">)', SITE + "/en/pricing/")

    # data-en holds the English inner HTML of its element
    def swap(m):
        tag, attrs = m.group(1), m.group(2)
        val = html.unescape(re.search(r'data-en="([^"]*)"', attrs).group(1))
        return f"<{tag}{attrs}>{val}</{tag}>"
    count = 0
    while True:
        new = re.sub(r'<(\w+)((?:[^>](?!data-en=))*?\sdata-en="[^"]*"[^>]*)>(?:(?!<\1[\s>]).)*?</\1>', swap, en, count=0, flags=re.S)
        if new == en:
            break
        en = new
        count += 1
        if count > 3:
            break
    en = re.sub(r'(<[^>]*\sdata-book[^>]*\shref=")[^"]*(")', r"\1/en/#contact\2", en)
    en = re.sub(r'(<[^>]*\shref=")[^"]*("[^>]*\sdata-book)', r"\1/en/#contact\2", en)
    en = re.sub(r'(<[^>]*\shref=")[^"]*("[^>]*\sdata-home)', r"\1/en/\2", en)
    en = re.sub(r'(<[^>]*\sdata-home[^>]*\shref=")[^"]*(")', r"\1/en/\2", en)
    en = re.sub(r'(<[^>]*\shref=")[^"]*("[^>]*\sdata-demo)', r"\1/cdcp/\2", en)
    en = re.sub(r'(<[^>]*\sdata-demo[^>]*\shref=")[^"]*(")', r"\1/cdcp/\2", en)
    for a, b in (('aria-label="Principal"', 'aria-label="Main"'), ('aria-label="Pied de page"', 'aria-label="Footer"'),
                 ('aria-label="SSS Marketing, accueil"', 'aria-label="SSS Marketing, home"'),
                 ('id="lang-fr" aria-current="true"', 'id="lang-fr"'),
                 ('id="lang-en">', 'id="lang-en" aria-current="true">')):
        en = en.replace(a, b)
    out = ROOT / "en" / "pricing" / "index.html"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(en, encoding="utf-8")
    print("wrote en/pricing/index.html")


if __name__ == "__main__":
    home()
    pricing()
